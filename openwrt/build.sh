#!/usr/bin/env bash
# Build a ready-to-flash OpenWrt image with tuya-homekit-bridge, your network
# settings and (optionally) your existing HomeKit pairing baked in.
#
# Usage:  cp build.example.env build.env && $EDITOR build.env && ./build.sh
# Needs:  Docker (the OpenWrt Image Builder runs in a linux/amd64 container).
#
# Because everything is part of the image's defaults, a factory reset of the
# router (reset button) brings back exactly this configuration.
set -euo pipefail
cd "$(dirname "$0")"

ENV_FILE=${1:-build.env}
[ -f "$ENV_FILE" ] || { echo "missing $ENV_FILE (copy build.example.env)"; exit 1; }
# shellcheck disable=SC1090
case "$ENV_FILE" in /*) . "$ENV_FILE" ;; *) . "./$ENV_FILE" ;; esac

: "${RELEASE:?}" "${TARGET:?}" "${PROFILE:?}" "${LAN_IP:?}" "${BRIDGE_CONFIG:?}" "${BRIDGE_URL:?}" "${BRIDGE_SHA256:?set BRIDGE_SHA256 (see sha256sums.txt of the release)}"

WORK=work
OUT=out
rm -rf "$WORK/files"
mkdir -p "$WORK/files" "$OUT"
cp -R files/. "$WORK/files/"

# quote VALUE for use inside a single-quoted shell string
q() { printf "'%s'" "$(printf '%s' "$1" | sed "s/'/'\\\\''/g")"; }

# --- bridge files -----------------------------------------------------------------
B="$WORK/files/etc/tuya-homekit-bridge"
mkdir -p "$B"
cp "$BRIDGE_CONFIG" "$B/config.json"
if [ -n "${BRIDGE_DB:-}" ]; then
	mkdir -p "$B/db" && cp -R "$BRIDGE_DB/." "$B/db/"
fi
{
	echo "URL=$(q "$BRIDGE_URL")"
	echo "SHA256=$(q "$BRIDGE_SHA256")"
} > "$B/loader.conf"

# --- SSH keys ------------------------------------------------------------------------
if [ -n "${SSH_AUTHORIZED_KEYS_FILE:-}" ]; then
	mkdir -p "$WORK/files/etc/dropbear"
	cat "${SSH_AUTHORIZED_KEYS_FILE/#\~/$HOME}" > "$WORK/files/etc/dropbear/authorized_keys"
fi

# --- first-boot settings (uci-defaults) -----------------------------------------------
mkdir -p "$WORK/files/etc/uci-defaults"
S="$WORK/files/etc/uci-defaults/90-tuya-homekit-site"
cat > "$S" <<EOF
#!/bin/sh
# Generated by tuya-homekit-bridge/openwrt/build.sh

uci set system.@system[0].hostname=$(q "${HOSTNAME:-OpenWrt}")
# OpenWrt >= 24 stores the LAN address as a CIDR list ("192.168.1.1/24"); replace it
# with address + netmask so it works with both formats.
uci -q delete network.lan.ipaddr
uci -q delete network.lan.netmask
uci set network.lan.ipaddr=$(q "$LAN_IP")
uci set network.lan.netmask=$(q "${LAN_NETMASK:-255.255.255.0}")

WAN_PROTO=$(q "${WAN_PROTO:-dhcp}")
WAN_VLAN=$(q "${WAN_VLAN:-}")
WANDEV=\$(uci -q get network.wan.device)
if [ -n "\$WAN_VLAN" ] && [ -n "\$WANDEV" ]; then
	BASE=\${WANDEV%.*}; SUB=\${WANDEV##*.}
	SV=""
	# swconfig boards: WAN is a switch VLAN (e.g. eth0.2). Retag that switch VLAN
	# instead of stacking a second 802.1Q header on top of it.
	if [ "\$BASE" != "\$WANDEV" ]; then
		for s in \$(uci show network | sed -n 's/^network\.\([^.=]*\)=switch_vlan\$/\1/p'); do
			[ "\$(uci -q get network.\$s.vlan)" = "\$SUB" ] && SV=\$s
		done
	fi
	if [ -n "\$SV" ]; then
		ports=""
		for p in \$(uci get network.\$SV.ports); do
			case "\$p" in *t) ports="\$ports \$p";; *) ports="\$ports \${p}t";; esac
		done
		uci set network.\$SV.vid="\$WAN_VLAN"
		uci set network.\$SV.ports="\${ports# }"
		NEWDEV="\$BASE.\$WAN_VLAN"
	else
		uci set network.wanvlan=device
		uci set network.wanvlan.type='8021q'
		uci set network.wanvlan.ifname="\$WANDEV"
		uci set network.wanvlan.vid="\$WAN_VLAN"
		uci set network.wanvlan.name="\$WANDEV.\$WAN_VLAN"
		NEWDEV="\$WANDEV.\$WAN_VLAN"
	fi
	uci set network.wan.device="\$NEWDEV"
	uci -q get network.wan6 >/dev/null && uci set network.wan6.device="\$NEWDEV"
fi
uci set network.wan.proto="\$WAN_PROTO"
if [ "\$WAN_PROTO" = pppoe ]; then
	uci set network.wan.username=$(q "${PPPOE_USER:-}")
	uci set network.wan.password=$(q "${PPPOE_PASS:-}")
	uci -q get network.wan6 >/dev/null && uci set network.wan6.device='@wan'
fi

for alias in ${LAN_ALIASES:-}; do
	uci add_list dhcp.@dnsmasq[0].address="/\$alias/$LAN_IP"
done

WIFI_SSID=$(q "${WIFI_SSID:-}")
if [ -n "\$WIFI_SSID" ]; then
	for r in \$(uci show wireless | sed -n 's/^wireless\.\([^.=]*\)=wifi-device$/\1/p'); do
		uci set wireless.\$r.disabled='0'
		uci set wireless.\$r.country=$(q "${WIFI_COUNTRY:-US}")
		iface=default_\$r
		uci -q get wireless.\$iface >/dev/null || { uci set wireless.\$iface=wifi-iface; uci set wireless.\$iface.device=\$r; uci set wireless.\$iface.mode='ap'; uci set wireless.\$iface.network='lan'; }
		uci set wireless.\$iface.ssid="\$WIFI_SSID"
		uci set wireless.\$iface.encryption='psk2'
		uci set wireless.\$iface.key=$(q "${WIFI_KEY:-}")
		uci set wireless.\$iface.disabled='0'
	done
fi

if [ -s /etc/dropbear/authorized_keys ]; then
	chmod 600 /etc/dropbear/authorized_keys
	uci set dropbear.@dropbear[0].PasswordAuth='off'
	uci set dropbear.@dropbear[0].RootPasswordAuth='off'
fi

# Optional second network on every radio, e.g. the SSID printed on the router's
# label, so the label stays valid. 5 GHz radios get WIFI2_SSID_5G (default: <ssid>_5G).
WIFI2_SSID=$(q "${WIFI2_SSID:-}")
if [ -n "\$WIFI2_SSID" ]; then
	for r in \$(uci show wireless | sed -n 's/^wireless\.\([^.=]*\)=wifi-device$/\1/p'); do
		ssid="\$WIFI2_SSID"
		[ "\$(uci -q get wireless.\$r.band)" = 5g ] && ssid=$(q "${WIFI2_SSID_5G:-${WIFI2_SSID}_5G}")
		i=secondary_\$r
		uci set wireless.\$i=wifi-iface
		uci set wireless.\$i.device=\$r
		uci set wireless.\$i.mode='ap'
		uci set wireless.\$i.network='lan'
		uci set wireless.\$i.ssid="\$ssid"
		uci set wireless.\$i.encryption='psk2'
		uci set wireless.\$i.key=$(q "${WIFI2_KEY:-}")
	done
fi

# Optional root password (web UI login). Without it OpenWrt asks you to set one.
ROOT_PASSWORD=$(q "${ROOT_PASSWORD:-}")
if [ -n "\$ROOT_PASSWORD" ]; then
	printf '%s\n%s\n' "\$ROOT_PASSWORD" "\$ROOT_PASSWORD" | passwd root >/dev/null 2>&1
fi

EOF
# optional site-specific uci commands
if [ -n "${EXTRA_UCI_DEFAULTS:-}" ]; then
	{ echo; echo "# --- extra ($EXTRA_UCI_DEFAULTS)"; cat "${EXTRA_UCI_DEFAULTS/#\~/$HOME}"; echo; } >> "$S"
fi
cat >> "$S" <<EOF
chmod 700 /etc/tuya-homekit-bridge
chmod 600 /etc/tuya-homekit-bridge/config.json
[ -d /etc/tuya-homekit-bridge/db ] && chmod -R go-rwx /etc/tuya-homekit-bridge/db

uci commit
/etc/init.d/tuya-homekit-bridge enable
exit 0
EOF
chmod 755 "$S"

# --- build ----------------------------------------------------------------------------
IB="openwrt-imagebuilder-$RELEASE-${TARGET/\//-}.Linux-x86_64"
URL="https://downloads.openwrt.org/releases/$RELEASE/targets/$TARGET/$IB.tar.zst"
[ -f "$WORK/$IB.tar.zst" ] || curl -fL -o "$WORK/$IB.tar.zst" "$URL"

docker run --rm --platform linux/amd64 -v "$PWD/$WORK":/work -v "$PWD/$OUT":/out debian:bookworm bash -euc "
	apt-get update -qq >/dev/null
	apt-get install -y -qq build-essential file gawk gettext libncurses-dev python3 python3-setuptools rsync unzip wget xsltproc zstd >/dev/null
	mkdir -p /ib && tar --zstd -xf /work/$IB.tar.zst -C /ib --strip-components=1
	cd /ib
	make image PROFILE='$PROFILE' PACKAGES='${PACKAGES:-}' FILES=/work/files
	cp bin/targets/$TARGET/*'$PROFILE'*.bin /out/
"
ls -l "$OUT"
echo "Done. Flash the *-factory.bin from the vendor web UI, or *-sysupgrade.bin from OpenWrt."
